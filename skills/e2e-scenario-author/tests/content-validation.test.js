'use strict';

// Scenario content checks: a catalog that is well-formed but would be refused by a
// correct server (issue cases: missing required parameter, constraint in the wrong
// location, invented enum constant, unrelated `prev.` capture) must not validate.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');

const discover = path.resolve(__dirname, '../scripts/discover-surfaces.js');
const validate = path.resolve(__dirname, '../scripts/validate-catalog.js');
const contract = path.resolve(__dirname, '../reference/e2e-scenario-contract.md');

function write(root, relative, content) {
  const file = path.join(root, relative);
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, content);
}

function repository(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vulpora-content-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  write(root, 'build.gradle.kts', 'plugins { id("org.springframework.boot") }\n');
  write(root, 'src/main/java/app/Intent.java', 'package app;\npublic enum Intent { REGISTER, UPDATE, ALL; }\n');
  write(root, 'src/main/java/app/LicenseReq.java', 'package app;\npublic record LicenseReq(@NotBlank String site, Intent intent) {}\n');
  write(root, 'src/main/java/app/AdminController.java', `package app;
@RestController
@RequestMapping("/v1")
class AdminController {
  @GetMapping("/cache-board")
  public String board(@RequestParam String family, @RequestParam(required = false) Integer page) { return ""; }
  @GetMapping("/codes/{code}")
  public String code(@PathVariable @Size(max = 10) String code) { return ""; }
  @PostMapping("/licenses")
  public String license(@Valid @RequestBody LicenseReq req) { return ""; }
}
`);
  const inventory = spawnSync(process.execPath, [discover, root, contract], {encoding: 'utf8'});
  assert.equal(inventory.status, 0, inventory.stderr);
  write(root, 'inventory.json', inventory.stdout);
  return {root, fingerprint: JSON.parse(inventory.stdout).source_fingerprint};
}

function scenario(id, target, request, {expected = '`200 OK`', mutates = '—', dependsOn = '—', captures = '—', notes = '—'} = {}) {
  const teardown = mutates === '—' ? '' : `\n\`\`\`shell\n# teardown\ncurl -X DELETE {{api}}/v1/${mutates}/{{prev.ID}}\n\`\`\`\n`;
  return `### \`${id}\` — scenario

| Field | Value |
|---|---|
| Target | \`${target}\` |
| Purpose | purpose |
| Preconditions | — |
| Dataset | — |
| Expected | ${expected} |
| Mutates | ${mutates} |
| Depends-on | ${dependsOn} |
| Captures | ${captures} |
| Notes | ${notes} |

\`\`\`http
${request}
\`\`\`
${teardown}`;
}

const BASE = {
  'E2E-V1-CACHE-BOARD-HAPPY': ['GET /v1/cache-board (:)', 'GET {{api}}/v1/cache-board?family=JOB'],
  'E2E-V1-CODES-BY-CODE-HAPPY': ['GET /v1/codes/{code} (:)', 'GET {{api}}/v1/codes/C1'],
  'E2E-V1-CODES-BY-CODE-VALIDATION-FAIL-CODE-SIZE': ['GET /v1/codes/{code} (:)', 'GET {{api}}/v1/codes/CCCCCCCCCCCCCCCC', {expected: '`400`'}],
  'E2E-V1-LICENSES-HAPPY': ['POST /v1/licenses (:)', 'POST {{api}}/v1/licenses\nContent-Type: application/json\n\n{"site":"S1","intent":"REGISTER"}', {mutates: 'licenses', captures: 'ID'}],
  'E2E-V1-LICENSES-VALIDATION-FAIL-SITE-NOT-BLANK': ['POST /v1/licenses (:)', 'POST {{api}}/v1/licenses\nContent-Type: application/json\n\n{"site":""}', {expected: '`400`'}],
};

function check(t, changes = {}, siblings = {}) {
  const {root, fingerprint} = repository(t);
  const entries = {...BASE, ...changes};
  const body = Object.keys(entries).sort().map((id) => scenario(id, ...entries[id])).join('\n');
  write(root, 'docs/e2e-scenarios/catalog.md', `<!-- AUTO-GENERATED by e2e-scenario-author. DO NOT EDIT. Human notes belong in docs/e2e-scenarios/notes.md. -->
<!-- Source fingerprint: sha256:${fingerprint} -->
<!-- Contract: docs/e2e-scenarios/CONTRACT.md version 1 -->

# E2E Scenario Catalog

${body}`);
  for (const [name, value] of Object.entries(siblings)) write(root, `docs/e2e-scenarios/${name}`, JSON.stringify(value));
  return spawnSync(process.execPath, [validate, path.join(root, 'docs/e2e-scenarios/catalog.md'), contract,
    path.join(root, 'inventory.json')], {encoding: 'utf8'});
}

test('A correct catalog validates against the request facts', t => {
  const result = check(t);
  assert.equal(result.status, 0, result.stderr);
});

test('Issue cases that a correct server refuses fail validation', t => {
  const cases = [
    [{'E2E-V1-CACHE-BOARD-HAPPY': ['GET /v1/cache-board (:)', 'GET {{api}}/v1/cache-board']}, /SCA-19\.MISSING-PARAM: E2E-V1-CACHE-BOARD-HAPPY:family/],
    [{'E2E-V1-CODES-BY-CODE-VALIDATION-FAIL-CODE-SIZE': ['GET /v1/codes/{code} (:)', 'GET {{api}}/v1/codes/C1?code=CCCCCCCCCCCCCCCC', {expected: '`400`'}]},
      /SCA-19\.CONSTRAINT-LOCATION: .*code is a path variable/],
    [{'E2E-V1-CODES-BY-CODE-HAPPY': ['GET /v1/codes/{code} (:)', 'GET {{api}}/v1/codes/{code}']}, /SCA-19\.UNFILLED-PATH/],
    [{'E2E-V1-LICENSES-HAPPY': ['POST /v1/licenses (:)', 'POST {{api}}/v1/licenses\n\n{"site":"S1","intent":"CREATE"}', {mutates: 'licenses', captures: 'ID'}]},
      /SCA-19\.BAD-ENUM: E2E-V1-LICENSES-HAPPY:intent=CREATE not in REGISTER\|UPDATE\|ALL/],
    [{'E2E-V1-CACHE-BOARD-HAPPY': ['GET /v1/cache-board (:)', 'GET {{api}}/v1/cache-board?family={{prev.DIGEST}}']},
      /SCA-15\.BAD-PREV-SOURCE: E2E-V1-CACHE-BOARD-HAPPY:DIGEST/],
  ];
  for (const [change, pattern] of cases) {
    const result = check(t, change);
    assert.notEqual(result.status, 0, String(pattern));
    assert.match(result.stderr, pattern);
  }
});

test('Human overrides survive regeneration and orphaned overrides surface', t => {
  const overrides = {schema: 'vulpora.e2e-scenario-overrides/v1', scenarios: {
    'E2E-V1-CACHE-BOARD-HAPPY': {priority: 'P0', assertions: ['assert $.refreshTargets[*].site == ["SITE-A","ALL"]']},
  }};
  const ok = check(t, {}, {'scenario-overrides.json': overrides});
  assert.equal(ok.status, 0, ok.stderr);
  assert.equal(JSON.parse(ok.stdout).override_count, 1);

  const orphan = check(t, {}, {'scenario-overrides.json': {...overrides, scenarios: {'E2E-GONE-HAPPY': {priority: 'P0'}}}});
  assert.match(orphan.stderr, /SCA-15\.ORPHAN-OVERRIDE: E2E-GONE-HAPPY/);
  const bad = check(t, {}, {'scenario-overrides.json': {...overrides, scenarios: {'E2E-V1-CACHE-BOARD-HAPPY': {assertions: ['assert $.x ~ 1']}}}});
  assert.match(bad.stderr, /SCA-15\.BAD-ASSERTION/);
});

test('Held scenarios and registered scenario exclusions are reported, expired ones block', t => {
  const held = check(t, {'E2E-V1-CACHE-BOARD-HAPPY': ['GET /v1/cache-board (:)', 'GET {{api}}/v1/cache-board?family=JOB', {notes: 'hold: family values need a seed fixture'}]},
    {'known-deviations.json': {schema: 'vulpora.e2e-known-deviations/v1', deviations: [
      {kind: 'scenario-exclusion', scenario: 'E2E-V1-LICENSES-HAPPY', reason: 'needs license server stub', approvedBy: 'qa-lead', expires: '2999-01-01'},
    ]}});
  assert.equal(held.status, 0, held.stderr);
  const output = JSON.parse(held.stdout);
  assert.deepEqual(output.held, [{scenario: 'E2E-V1-CACHE-BOARD-HAPPY', reason: 'family values need a seed fixture'}]);
  assert.equal(output.scenario_exclusions[0].approvedBy, 'qa-lead');

  const expired = check(t, {}, {'known-deviations.json': {schema: 'vulpora.e2e-known-deviations/v1', deviations: [
    {kind: 'scenario-exclusion', scenario: 'E2E-V1-LICENSES-HAPPY', reason: 'r', approvedBy: 'a', expires: '2000-01-01'},
  ]}});
  assert.match(expired.stderr, /SCA-5\.3: .*deviation expired on 2000-01-01/);
});
