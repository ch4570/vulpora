'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawnSync} = require('node:child_process');

const discover = path.resolve(__dirname, '../scripts/discover-surfaces.js');
const validate = path.resolve(__dirname, '../scripts/validate-catalog.js');
const contract = path.resolve(__dirname, '../reference/e2e-scenario-contract.md');
const REGISTRY = 'docs/e2e-scenarios/known-deviations.json';

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vulpora-catalog-ext-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  write(root, 'build.gradle.kts', 'plugins { id("org.springframework.boot") }\n');
  write(root, 'src/main/java/app/HealthController.java', `package app;
@RestController
class HealthController {
  @GetMapping("/health")
  public String health() { return "ok"; }
}
`);
  // Unsupported today: component-level nested validation stops discovery.
  write(root, 'src/main/java/app/NestedReq.java', 'package app;\npublic record NestedReq(@Valid Target target) {}\n');
  write(root, 'src/main/java/app/NestedController.java', `package app;
@RestController
class NestedController {
  @PostMapping("/nested")
  public String create(@Valid @RequestBody NestedReq req) { return "ok"; }
}
`);
  return root;
}

function write(root, relative, content) {
  const file = path.join(root, relative);
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, content);
}

function registry(root, deviations) {
  write(root, REGISTRY, JSON.stringify({schema: 'vulpora.e2e-known-deviations/v1', deviations}));
}

function run(root) {
  return spawnSync(process.execPath, [discover, root, contract], {encoding: 'utf8'});
}

const nested = {approvedBy: 'qa-lead', expires: '2999-12-31', path: 'src/main/java/app/NestedController.java', reason: 'nested @Valid DTO pending collector support'};
const discovery = {kind: 'discovery-exclusion', ...nested};

test('A registered, unexpired exclusion skips only that source and is recorded in the inventory', t => {
  const root = fixture(t);
  assert.match(run(root).stderr, /SCA-5\.2: .*NestedController\.java/);
  registry(root, [discovery]);
  const result = run(root);
  assert.equal(result.status, 0, result.stderr);
  const inventory = JSON.parse(result.stdout);
  assert.deepEqual(inventory.surfaces.map(surface => surface.target), ['GET /health (:)']);
  assert.deepEqual(inventory.excluded_sources, [nested]);
  assert.ok(inventory.inputs.includes(nested.path), 'excluded sources stay fingerprinted');

  // Changing the reviewed registry changes the fingerprint, so the catalog goes stale.
  registry(root, [{...discovery, reason: 'different reason'}]);
  assert.notEqual(JSON.parse(run(root).stdout).source_fingerprint, inventory.source_fingerprint);

  // Scenario exclusions are not discovery inputs and never make the catalog stale.
  registry(root, [discovery, {kind: 'scenario-exclusion', scenario: 'E2E-X-HAPPY', reason: 'r', approvedBy: 'a', expires: '2999-12-31'}]);
  assert.equal(JSON.parse(run(root).stdout).source_fingerprint, inventory.source_fingerprint);
});

test('Expired, unknown, or incomplete exclusions fail closed', t => {
  const root = fixture(t);
  for (const [entry, pattern] of [
    [{...discovery, expires: '2000-01-01'}, /deviation expired on 2000-01-01/],
    [{...discovery, path: 'src/main/java/app/Missing.java'}, /not a discovered source file/],
    [{...discovery, reason: ' '}, /reason is required/],
    [{...discovery, approvedBy: ''}, /approvedBy is required/],
    [{...discovery, expires: '31/12/2999'}, /expires must be YYYY-MM-DD/],
    [{...discovery, kind: 'skip'}, /kind must be/],
  ]) {
    registry(root, [entry]);
    const result = run(root);
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, new RegExp(`^SCA-5\\.3: ${REGISTRY.replaceAll('.', '\\.')}: .*${pattern.source}`));
  }
});

test('A repository without a registry keeps its existing inventory shape', t => {
  const root = fixture(t);
  fs.rmSync(path.join(root, 'src/main/java/app/NestedController.java'));
  const inventory = JSON.parse(run(root).stdout);
  assert.equal(Object.hasOwn(inventory, 'excluded_sources'), false);
});

function catalog(expected) {
  return `<!-- AUTO-GENERATED by e2e-scenario-author. DO NOT EDIT. Human notes belong in docs/e2e-scenarios/notes.md. -->
<!-- Source fingerprint: sha256:${'0'.repeat(64)} -->
<!-- Contract: docs/e2e-scenarios/CONTRACT.md version 1 -->

# E2E Scenario Catalog

### \`E2E-CACHE-PREVIEW-HAPPY\` — Preview proposes only the selected brand

| Field | Value |
|---|---|
| Target | \`GET /preview (:)\` |
| Purpose | Preview lists refresh targets for the selected brand only |
| Preconditions | — |
| Dataset | — |
| Expected | ${expected} |
| Mutates | — |
| Depends-on | — |
| Captures | — |
| Notes | — |

\`\`\`http
GET {{api}}/preview
\`\`\`
`;
}

function validateCatalog(t, expected) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vulpora-catalog-assert-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  fs.writeFileSync(path.join(root, 'catalog.md'), catalog(expected));
  return spawnSync(process.execPath, [validate, path.join(root, 'catalog.md'), contract], {encoding: 'utf8'});
}

test('Expected accepts machine-checked body assertions alongside free text', t => {
  const result = validateCatalog(t,
    '`200 OK`; assert $.refreshTargets contains "SITE-A"; assert $.refreshTargets excludes "SITE-B"; assert $.items[0].id exists; response is cached');
  assert.equal(result.status, 0, result.stderr);
});

test('Malformed assert clauses are rejected instead of silently ignored', t => {
  for (const clause of ['assert refreshTargets contains "X"', 'assert $.a ~= 1', 'assert $.a == SITE-A', 'assert $.a contains']) {
    const result = validateCatalog(t, `\`200 OK\`; ${clause}`);
    assert.notEqual(result.status, 0, clause);
    assert.match(result.stderr, /^SCA-15\.BAD-ASSERTION: E2E-CACHE-PREVIEW-HAPPY:/);
  }
});
