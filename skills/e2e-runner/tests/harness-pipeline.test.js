'use strict';

// plan -> repository harness observations -> assembled result -> validator -> verdict.
// The harness here is simulated; the Java example is compiled and run when a JDK and
// Jackson are available locally (it never downloads anything).

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const {spawnSync, spawn} = require('node:child_process');

const scripts = path.resolve(__dirname, '../scripts');
const node = (script, ...args) => spawnSync(process.execPath, [path.join(scripts, script), ...args], {encoding: 'utf8'});

function scenario(id, target, expected, request, {mutates = '—', dependsOn = '—', captures = '—', notes = '—', teardown = null} = {}) {
  return `### \`${id}\` — ${id}

| Field | Value |
|---|---|
| Target | \`${target}\` |
| Purpose | purpose |
| Preconditions | — |
| Dataset | — |
| Expected | ${expected} |
| Mutates | ${mutates} |
| Depends-on | ${dependsOn} |
| Captures | ${captures} |
| Notes | ${notes} |

\`\`\`http
${request}
\`\`\`
${teardown ? `\n\`\`\`shell\n# teardown\n${teardown}\n\`\`\`\n` : ''}`;
}

function workspace(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'vulpora-harness-'));
  t.after(() => fs.rmSync(root, {recursive: true, force: true}));
  fs.mkdirSync(path.join(root, 'docs/e2e-scenarios'), {recursive: true});
  const blocks = [
    scenario('E2E-V1-BOARD-HAPPY', 'GET /v1/board (:)', '`200 OK`', 'GET {{api}}/v1/board?family=JOB'),
    scenario('E2E-V1-CLIENTS-BY-ID-GET-HAPPY', 'GET /v1/clients/{id} (:)', '`200 OK`; assert $.name == "c1"',
      'GET {{api}}/v1/clients/{{prev.ID}}', {dependsOn: '[E2E-V1-CLIENTS-POST-HAPPY]'}),
    scenario('E2E-V1-CLIENTS-POST-HAPPY', 'POST /v1/clients (:)', '`201`', 'POST {{api}}/v1/clients\n\n{"name":"c1"}',
      {mutates: 'clients', captures: 'ID', teardown: 'curl -sf -X DELETE {{api}}/v1/clients/{{prev.ID}}'}),
    scenario('E2E-V1-EXPORT-HAPPY', 'GET /v1/export (:)', '`200`', 'GET {{api}}/v1/export', {notes: 'hold: export needs an object-store stub'}),
    scenario('E2E-V1-PING-HAPPY', 'GET /v1/ping (:)', '`204`', 'GET {{api}}/v1/ping'),
  ];
  fs.writeFileSync(path.join(root, 'docs/e2e-scenarios/catalog.md'), `<!-- AUTO-GENERATED by e2e-scenario-author. DO NOT EDIT. Human notes belong in docs/e2e-scenarios/notes.md. -->
<!-- Source fingerprint: sha256:${'a'.repeat(64)} -->
<!-- Contract: docs/e2e-scenarios/CONTRACT.md version 1 -->

# E2E Scenario Catalog

${blocks.join('\n')}`);
  fs.writeFileSync(path.join(root, 'docs/e2e-scenarios/scenario-overrides.json'), JSON.stringify({
    schema: 'vulpora.e2e-scenario-overrides/v1',
    scenarios: {'E2E-V1-BOARD-HAPPY': {assertions: ['assert $.refreshTargets[*].site == ["SITE-A"]']}},
  }));
  const plan = node('export-catalog-plan.js', path.join(root, 'docs/e2e-scenarios/catalog.md'));
  assert.equal(plan.status, 0, plan.stderr);
  fs.writeFileSync(path.join(root, 'plan.json'), plan.stdout);
  return {root, plan: JSON.parse(plan.stdout)};
}

test('The plan orders dependencies, defers the parent teardown, and explains every unselected scenario', t => {
  const {plan} = workspace(t);
  const ids = plan.scenarios.map((item) => item.id);
  assert.ok(ids.indexOf('E2E-V1-CLIENTS-POST-HAPPY') < ids.indexOf('E2E-V1-CLIENTS-BY-ID-GET-HAPPY'));
  const post = plan.scenarios.find((item) => item.id === 'E2E-V1-CLIENTS-POST-HAPPY');
  assert.equal(post.teardownAfter, 'E2E-V1-CLIENTS-BY-ID-GET-HAPPY');
  assert.deepEqual(plan.scenarios.find((item) => item.id === 'E2E-V1-CLIENTS-BY-ID-GET-HAPPY').runTeardownsAfter, [post.id]);
  const held = plan.scenarios.find((item) => item.id === 'E2E-V1-EXPORT-HAPPY');
  assert.equal(held.selected, false);
  assert.equal(held.unselectedReason, 'held by author: export needs an object-store stub');
  assert.match(plan.scenarios[0].expected, /assert \$\.refreshTargets\[\*\]\.site == \["SITE-A"\]$/);
});

function writeBody(root, id, value) {
  fs.mkdirSync(path.join(root, 'out'), {recursive: true});
  fs.writeFileSync(path.join(root, 'out', `${id}.txt`), typeof value === 'string' ? value : JSON.stringify(value));
  return `${id}.txt`;
}

function observations(root, results) {
  const file = path.join(root, 'out', 'observations.json');
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, JSON.stringify({
    schema: 'vulpora.e2e-harness-observations/v1', runId: 'run-1', startedAt: '2026-11-02T00:00:00Z',
    finishedAt: '2026-11-02T00:00:05Z', environment: {owner: 'repository-harness', images: ['postgres:16']}, results,
    lifecycle: {cleanup: {status: 'PASS'}, teardown: {status: 'PASS'}, orphanAudit: {status: 'PASS'},
      absenceProbes: [{id: 'clients-empty', status: 'PASS'}]},
  }));
  return file;
}

test('Assembled results catch the business-rule bug and the 204/404 mismatch, and mask secrets', t => {
  const {root} = workspace(t);
  const file = observations(root, {
    'E2E-V1-BOARD-HAPPY': {executed: true, httpStatus: 200, latencyMs: 4, bodyFile: writeBody(root, 'board', {refreshTargets: [{site: 'SITE-A'}, {site: 'SITE-B'}]})},
    'E2E-V1-CLIENTS-POST-HAPPY': {executed: true, httpStatus: 201, latencyMs: 3, bodyFile: writeBody(root, 'post', {id: 1, apiKey: 'sk-live-1'}), teardown: {status: 'PASS'}},
    'E2E-V1-CLIENTS-BY-ID-GET-HAPPY': {executed: true, httpStatus: 200, latencyMs: 2, bodyFile: writeBody(root, 'get', {name: 'c1'}), vars: {'prev.ID': '1'}},
    'E2E-V1-PING-HAPPY': {executed: true, httpStatus: 404, latencyMs: 1, bodyFile: writeBody(root, 'ping', '')},
  });
  const assembled = node('assemble-run-result.js', path.join(root, 'plan.json'), file, path.join(root, 'report'));
  assert.equal(assembled.status, 0, assembled.stderr);
  const runPath = path.join(root, 'report', 'run-1.json');
  const run = JSON.parse(fs.readFileSync(runPath, 'utf8'));
  const status = Object.fromEntries(run.results.map((result) => [result.id, result.status]));
  assert.deepEqual(status, {
    'E2E-V1-BOARD-HAPPY': 'FAIL', 'E2E-V1-CLIENTS-POST-HAPPY': 'PASS', 'E2E-V1-CLIENTS-BY-ID-GET-HAPPY': 'PASS', 'E2E-V1-PING-HAPPY': 'FAIL',
  });
  assert.deepEqual(run.notSelected, [{reason: 'held by author: export needs an object-store stub', count: 1, caseIds: ['E2E-V1-EXPORT-HAPPY']}]);
  assert.match(fs.readFileSync(path.join(root, 'report/raw/E2E-V1-CLIENTS-POST-HAPPY.json'), 'utf8'), /"apiKey": "\*\*\*"/);
  assert.ok(fs.existsSync(path.join(root, 'report', 'run-1.done')));
  assert.equal(node('validate-run-result.js', runPath, '--require-done').status, 0);
  const verdict = JSON.parse(node('evaluate-run-verdict.js', runPath).stdout);
  assert.equal(verdict.verdict, 'INCONCLUSIVE');
  assert.deepEqual(verdict.notSelected[0].caseIds, ['E2E-V1-EXPORT-HAPPY']);
});

test('A dependent that ran after a failed parent counts as FAILED-DEPENDENCY', t => {
  const {root} = workspace(t);
  const file = observations(root, {
    'E2E-V1-CLIENTS-POST-HAPPY': {executed: true, httpStatus: 500, latencyMs: 3, bodyFile: writeBody(root, 'post', '{}'), teardown: {status: 'PASS'}},
    'E2E-V1-CLIENTS-BY-ID-GET-HAPPY': {executed: true, httpStatus: 200, latencyMs: 2, bodyFile: writeBody(root, 'get', {name: 'c1'})},
  });
  assert.equal(node('assemble-run-result.js', path.join(root, 'plan.json'), file, path.join(root, 'report')).status, 0);
  const run = JSON.parse(fs.readFileSync(path.join(root, 'report', 'run-1.json'), 'utf8'));
  assert.equal(run.results.find((result) => result.id === 'E2E-V1-CLIENTS-BY-ID-GET-HAPPY').status, 'FAILED-DEPENDENCY');
  const validated = node('validate-run-result.js', path.join(root, 'report', 'run-1.json'));
  assert.equal(validated.status, 0, validated.stdout);
});

test('A hand-written result that skipped the status comparison is rejected', t => {
  const {root} = workspace(t);
  const run = {
    schemaVersion: 1, contractVersion: 1, runId: 'r', startedAt: '2026-11-02T00:00:00Z', finishedAt: '2026-11-02T00:00:01Z',
    environment: {}, catalog: {}, scope: {requested: ['*'], autoIncluded: []},
    summary: {total: 1, pass: 1, fail: 0, skipped: 0, failedDependency: 0, probeError: 0},
    results: [{id: 'E2E-V1-PING-HAPPY', status: 'PASS', target: 'GET /v1/ping (:)', dataset: {}, dependsOn: [], actual: '404',
      expected: '`204`', latencyMs: 1, skippedReason: null, evidence: {rawBodyPath: null}, assertions: [], token: 'abc'}],
    selection: {collectedCount: 1}, execution: {supportedStack: true, slowTestExclusions: []},
    testCases: [{id: 'E2E-V1-PING-HAPPY', priority: 'P0', selected: true, executed: true, status: 'PASS', assertions: []}],
    lifecycle: {cleanup: {status: 'PASS'}, teardown: {status: 'PASS'}, orphanAudit: {status: 'PASS'}, absenceProbes: [{id: 'p', status: 'PASS'}]},
  };
  fs.writeFileSync(path.join(root, 'bad.json'), JSON.stringify(run));
  const result = node('validate-run-result.js', path.join(root, 'bad.json'));
  assert.equal(result.status, 1);
  const {errors, verdict} = JSON.parse(result.stdout);
  for (const pattern of [/PASS records no comparison/, /expected status 204 was never compared/, /requires evidence\.rawBodyPath/, /unmasked sensitive value at \$\.results\[0\]\.token/]) {
    assert.ok(errors.some((message) => pattern.test(message)), String(pattern));
  }
  assert.equal(verdict, 'INCONCLUSIVE');
});

function jacksonClasspath() {
  const base = path.join(os.homedir(), '.gradle/caches/modules-2/files-2.1/com.fasterxml.jackson.core');
  const find = (artifact) => {
    try {
      for (const version of fs.readdirSync(path.join(base, artifact)).filter((name) => name.startsWith('2.')).sort().reverse()) {
        for (const hash of fs.readdirSync(path.join(base, artifact, version))) {
          const jar = path.join(base, artifact, version, hash, `${artifact}-${version}.jar`);
          if (fs.existsSync(jar)) return jar;
        }
      }
    } catch { /* not cached */ }
    return null;
  };
  const jars = ['jackson-databind', 'jackson-core', 'jackson-annotations'].map(find);
  return jars.every(Boolean) && spawnSync('javac', ['-version']).status === 0 ? jars.join(path.delimiter) : null;
}

test('The Java example harness runs a plan end to end', {skip: jacksonClasspath() ? false : 'JDK or cached Jackson unavailable'}, async t => {
  const {root} = workspace(t);
  const classpath = jacksonClasspath();
  const clients = new Map();
  const server = http.createServer((request, response) => {
    let body = '';
    request.on('data', (chunk) => { body += chunk; }).on('end', () => {
      const send = (code, value) => { response.writeHead(code, {'content-type': 'application/json'}); response.end(value === undefined ? '' : JSON.stringify(value)); };
      const url = new URL(request.url, 'http://local');
      const match = url.pathname.match(/^\/v1\/clients\/(\d+)$/);
      if (url.pathname === '/v1/board') return send(200, {refreshTargets: [{site: 'SITE-A'}]});
      if (request.method === 'POST' && url.pathname === '/v1/clients') { clients.set('7', JSON.parse(body)); return send(201, {id: 7, apiKey: 'k'}); }
      if (match && request.method === 'GET') return clients.has(match[1]) ? send(200, clients.get(match[1])) : send(404, {});
      if (match && request.method === 'DELETE') return clients.delete(match[1]) ? send(204) : send(404, {});
      return send(204);
    });
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.close());
  const driver = path.join(root, 'Main.java');
  fs.writeFileSync(driver, `import example.e2e.CatalogPlanRunner;
import com.fasterxml.jackson.databind.ObjectMapper;
public class Main { public static void main(String[] a) throws Exception {
  ObjectMapper json = new ObjectMapper();
  CatalogPlanRunner runner = new CatalogPlanRunner(java.nio.file.Path.of(a[0]), "java-run");
  runner.run(java.nio.file.Path.of(a[1]), a[2], java.util.Map.of());
  var probes = json.createArrayNode(); probes.addObject().put("id", "clients-empty").put("status", "PASS");
  runner.writeObservations(json.createObjectNode(), "PASS", probes);
} }
`);
  const compiled = spawnSync('javac', ['-d', path.join(root, 'classes'), '-cp', classpath,
    path.resolve(__dirname, '../reference/examples/CatalogPlanRunner.java'), driver], {encoding: 'utf8'});
  assert.equal(compiled.status, 0, compiled.stderr);
  const port = server.address().port;
  const java = spawn('java', ['-cp', `${path.join(root, 'classes')}${path.delimiter}${classpath}`, 'Main', path.join(root, 'out'),
    path.join(root, 'plan.json'), `http://127.0.0.1:${port}`]);
  let stderr = '';
  java.stderr.on('data', (chunk) => { stderr += chunk; });
  assert.equal(await new Promise((resolve) => java.on('close', resolve)), 0, stderr);
  assert.equal(clients.size, 0, 'deferred teardown removed the created client');
  fs.writeFileSync(path.join(root, 'audit.json'), JSON.stringify({status: 'PASS', remaining: [], attempts: [{elapsedMs: 0, remaining: 0}]}));
  const assembled = node('assemble-run-result.js', path.join(root, 'plan.json'), path.join(root, 'out/observations.json'),
    path.join(root, 'report'), '--orphan-audit', path.join(root, 'audit.json'));
  assert.equal(assembled.status, 0, assembled.stderr);
  assert.equal(node('validate-run-result.js', path.join(root, 'report/java-run.json'), '--require-done').status, 0);
  const verdict = JSON.parse(node('evaluate-run-verdict.js', path.join(root, 'report/java-run.json')).stdout);
  assert.equal(verdict.verdict, 'PASS', JSON.stringify(verdict.reasons));
});
