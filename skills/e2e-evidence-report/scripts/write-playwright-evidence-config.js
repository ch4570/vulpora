#!/usr/bin/env node
'use strict';
// Write a run-owned Playwright config overlay into the evidence directory. The
// overlay imports the repository's own config unchanged and only turns on
// video and screenshots for every test, forces retries to zero and moves test
// output under the evidence directory. The repository config is never edited.
const fs = require('node:fs');
const path = require('node:path');

const CONFIG_NAMES = ['playwright.config.ts', 'playwright.config.mts', 'playwright.config.js', 'playwright.config.mjs', 'playwright.config.cjs'];

function main(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) args[String(argv[i]).replace(/^--/, '')] = argv[i + 1];
  if (!args.repo || !args['evidence-dir']) {
    throw new Error('usage: write-playwright-evidence-config.js --repo <repository root> --evidence-dir <run evidence dir> [--config <relative config path>]');
  }
  const repo = fs.realpathSync(args.repo);
  const candidates = args.config ? [args.config] : CONFIG_NAMES;
  const found = candidates.map(name => path.join(repo, name)).find(file => fs.existsSync(file));
  if (!found) throw new Error(`PLAYWRIGHT_CONFIG_NOT_FOUND: ${candidates.join(', ')}`);
  const base = fs.realpathSync(found);
  if (path.relative(repo, base).startsWith('..')) throw new Error(`CONFIG_OUTSIDE_REPO: ${base}`);
  const evidenceDir = path.resolve(args['evidence-dir']);
  if (!path.relative(repo, evidenceDir).startsWith('..')) throw new Error(`EVIDENCE_DIR_INSIDE_REPO: ${evidenceDir}`);
  fs.mkdirSync(evidenceDir, {recursive: true});
  const outputDir = path.join(evidenceDir, 'playwright-output');
  const evidenceUse = "video: 'on', screenshot: 'on', trace: 'retain-on-failure'";
  // Playwright resolves relative config paths against the config file, so paths
  // inherited from the base config are re-anchored to the base config's folder.
  const overlay = `// Generated by e2e-evidence-report. Run-owned; delete with the evidence directory.
import path from 'node:path';
import base from ${JSON.stringify(base)};

const baseDir = ${JSON.stringify(path.dirname(base))};
const anchor = value => (typeof value === 'string' ? path.resolve(baseDir, value) : value);
const anchorAll = value => (Array.isArray(value) ? value.map(anchor) : anchor(value));
const evidenceUse = { ${evidenceUse} };
const webServer = server => (server && server.cwd ? { ...server, cwd: anchor(server.cwd) } : server);

export default {
  ...base,
  testDir: anchor(base.testDir ?? '.'),
  ...(base.globalSetup ? { globalSetup: anchorAll(base.globalSetup) } : {}),
  ...(base.globalTeardown ? { globalTeardown: anchorAll(base.globalTeardown) } : {}),
  ...(base.webServer ? { webServer: Array.isArray(base.webServer) ? base.webServer.map(webServer) : webServer(base.webServer) } : {}),
  retries: 0,
  outputDir: ${JSON.stringify(outputDir)},
  use: { ...(base.use ?? {}), ...evidenceUse },
  projects: (base.projects ?? []).map(project => ({
    ...project,
    ...(project.testDir ? { testDir: anchor(project.testDir) } : {}),
    use: { ...(project.use ?? {}), ...evidenceUse },
  })),
};
`;
  const file = path.join(evidenceDir, `playwright.evidence.config${path.extname(base) === '.ts' || path.extname(base) === '.mts' ? '.ts' : '.mjs'}`);
  fs.writeFileSync(file, overlay);
  return {config: file, base_config: base, output_dir: outputDir, command_hint: `npx playwright test --config ${JSON.stringify(file)}`};
}

if (require.main === module) {
  try {
    process.stdout.write(`${JSON.stringify(main(process.argv.slice(2)), null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exit(2);
  }
}

module.exports = {main};
